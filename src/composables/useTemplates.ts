/**
 * 仅导出与装饰/排版相关的字段：排除主图与位置/变换，
 * 并剔除当前照片的 EXIF 内容（型号 / EXIF 文本 / 日期 / 镜头 / 品牌）。
 * 后者属于每张照片自身数据，存进模板会把 A 照片的型号带到 B 照片上。
 * 显示开关（showXxx）属于模板设计的一部分，正常保留。
 */
function toTemplateConfig(cfg: FrameConfig): Partial<FrameConfig> {
  const { photoSrc, photoX, photoY, photoRotation, photoCrop, bgScale, bgOffsetX, bgOffsetY, ...rest } = cfg
  void photoSrc
  void photoX
  void photoY
  void photoRotation
  void photoCrop
  void bgScale
  void bgOffsetX
  void bgOffsetY
  // 照片自身内容：不进模板（遥测与 exifRaw 同理——GPX 数据属于每张照片/活动自身）
  const {
    cameraModel,
    exifText,
    exifRaw,
    dateText,
    lensText,
    brand,
    telemetry,
    ...tpl
  } = rest
  void cameraModel
  void exifText
  void exifRaw
  void dateText
  void lensText
  void brand
  void telemetry
  return { ...tpl }
}

